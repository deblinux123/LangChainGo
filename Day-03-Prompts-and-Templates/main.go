type Summerizer struct {
	model    llms.Model
	template prompts.PromptTemplate
}

func NewSummerizer(modelName string) (*Summerizer, error) {
	model, err := ollama.New(
		ollama.WithModel(modelName),
	)

	if err != nil {
		return nil, fmt.Errorf("Create model: %w", err)
	}

	template := prompts.NewPromptTemplate(
		`You are a text summarization assistant.

Summarize the following text:
{{.text}}

Requirements:
- Language: {{.language}}
- Maximum sentences: {{.max_sentences}}`,
		[]string{"text", "language", "max_sentences"},
	)

	return &Summerizer{
		model:    model,
		template: template,
	}, nil
}

func (s *Summerizer) SummerizeText(
	ctx context.Context,
	text string,
	language string,
	maxSentences int,
) (string, error) {
	text = strings.TrimSpace(text)

	if text == "" {
		return "", fmt.Errorf("text cannot be empty")
	}

	if maxSentences <= 0 {
		return "", fmt.Errorf("maxSentences must be greater than 0.")
	}

	prompt, err := s.template.Format(map[string]any{
		"text":          text,
		"language":      language,
		"max_sentences": maxSentences,
	})

	if err != nil {
		return "", fmt.Errorf("format prompt: %w", err)
	}

	response, err := s.model.GenerateContent(
		ctx,
		[]llms.MessageContent{
			llms.TextParts(llms.ChatMessageTypeHuman, prompt),
		},
	)

	if err != nil {
		return "", fmt.Errorf("generate summery: %w", err)
	}

	if len(response.Choices) == 0 {
		return "", fmt.Errorf("model returned no response.")
	}

	return strings.TrimSpace(response.Choices[0].Content), nil
}

